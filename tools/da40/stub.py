"""Носок центроплана: короб-коллектор воздуха пассажиров и проходы трасс крыла сквозь нервюры.

AMM 21-00 2.B(2): передний лонжерон центроплана, внутренняя и наружная замыкающие нервюры левого
центроплана образуют короб-коллектор; воздух выходит через вырез в передней части внутренней
нервюры в поперечный шланг (к передней замыкающей нервюре правого центроплана), верх внутренней
нервюры каждого борта соединён с боковым каналом к дуге безопасности.
AMM 57-10 2.B(8), (9): жгут крыла (разъём P2400 / P2401 под креслом), шланг полного давления и
шланг сигнализатора сваливания (под креслом пилота) идут из крыла в кабину сквозь нервюры
центроплана — в резиновых втулках.

Здесь — общие точки: их берут трассы (pitot.py, electrical.py, air.py) и нервюры с вырезами
(air.py — внутренняя замыкающая, structure.py — передняя наружная, wing.py — корневая)."""
import math

from mathutils import Vector as V

INNER_RIB_X = 0.745     # внутренняя замыкающая нервюра (air.py)
OUTER_RIB_X = 1.19      # передняя наружная нервюра центроплана — она же наружная замыкающая (structure.py, STUB_X)
ROOT_RIB_X = 1.205      # корневая нервюра крыла (wing.py)
CS_FRONT_SPAR_Y = 0.012    # передняя стенка переднего главного шпангоута (structure.FRONT_MB)

# вырез под поперечный шланг: в передней нижней части внутренней нервюры — шланг сразу уходит под
# пол кабины перед передним главным шпангоутом и энергопоглощающими элементами кресел
PAX_HOLE = (-0.105, -0.135, 0.023)       # y, z, радиус (шланг 38 мм с хомутом)
SIDE_HOLE = (-0.050, -0.012, 0.017)      # верх внутренней нервюры: выход в боковой канал

# (y, z) прохода на внутренней нервюре; (y, z) на наружной и корневой; радиус трассы.
# Впереди переднего главного болта крыла: его головка и гайка выходят из переднего шпангоута
# вперёд до y −0,09 (x 1,02…1,07, z −0,09…−0,045), поэтому трассы в коробе-коллекторе идут
# ровно вдоль размаха при y −0,105…−0,145, над вырезом коллектора и над коробом NACA-заборника.
PASS = {
    'harness':    ((-0.105, -0.060), (-0.105, -0.060), 0.005),
    'pitot_heat': ((-0.125, -0.050), (-0.125, -0.050), 0.0035),    # два провода в одной втулке
    'stall':      ((-0.145, -0.060), (-0.145, -0.060), 0.005),
    'pitot':      ((-0.145, -0.080), (-0.145, -0.080), 0.004),
    'static':     ((-0.125, -0.075), (-0.125, -0.075), 0.004),     # в крыле статика — позади полного давления
    # труба молниеотвода поперечной ветви (bonding.py): над головкой переднего главного болта, как прежде
    'bonding':    ((-0.010, -0.025), (-0.010, -0.025), 0.0095),
    # кабель магнитометра GMU 44 из правого крыла (avionics.py) — на месте проводов обогрева ПВД левого борта
    'gmu':        ((-0.125, -0.050), (-0.125, -0.050), 0.003),
}
LH_ONLY = ('pitot_heat', 'stall', 'pitot', 'static')
RH_ONLY = ('gmu',)
GROMMET = 0.004          # толщина резиновой втулки по радиусу


def through(key, s=1):
    """Точки прохода трассы key сквозь внутреннюю, наружную и корневую нервюры борта s (+1 — левый)."""
    (yi, zi), (yo, zo), _ = PASS[key]
    return V((s * INNER_RIB_X, yi, zi)), V((s * OUTER_RIB_X, yo, zo)), V((s * ROOT_RIB_X, yo, zo))


def run(key, s=1, d=0.03):
    """Опорные точки трассы key от фюзеляжа к крылу: по прямой сквозь каждую втулку (за d до и после
    нервюры), иначе скругление углов трассы проводит её во втулке наискось."""
    i, o, r = through(key, s)
    dx = V((s * d, 0, 0))
    return [i - dx, i, i + dx, o - dx, o, r, r + dx]


def passes(rib, s=1):
    """[(центр, радиус трассы)] проходов на нервюре rib ('inner' | 'outer' | 'root') борта s."""
    x = {'inner': INNER_RIB_X, 'outer': OUTER_RIB_X, 'root': ROOT_RIB_X}[rib] * s
    out = []
    for key, (pi, po, r) in PASS.items():
        if (s < 0 and key in LH_ONLY) or (s > 0 and key in RH_ONLY):
            continue
        y, z = pi if rib == 'inner' else po
        out.append((V((x, y, z)), r))
    return out


def circle(c, r, n=20):
    """Контур круглого выреза в плоскости x = const."""
    return [V((c.x, c.y + r * math.cos(2 * math.pi * i / n), c.z + r * math.sin(2 * math.pi * i / n))) for i in range(n)]
